// Search-engine controls and response headers, all driven by config.indexable. Ported from dnsmailcheck's src/site/seo.ts.

import { config } from "../config";
import { HIT_INLINE_SHA256 } from "../lib/hits";

export const NOINDEX = "noindex, nofollow";

// Never in search, whatever config.indexable says: the admin pages, the API and the 404 page. Their responses carry X-Robots-Tag.
const PRIVATE_PREFIXES = ["/admin", "/api", "/404"];
export const RESULT_PARAMS: string[] = [];

/** True for a URL that stays noindex after launch. */
export function alwaysNoindex(url: URL): boolean {
  const path = url.pathname;
  if (PRIVATE_PREFIXES.some((p) => path === p || path.startsWith(`${p}/`) || path.startsWith(`${p}.`))) return true;
  return RESULT_PARAMS.some((k) => url.searchParams.has(k));
}

/** X-Robots-Tag for one response: every URL before launch, only the always-noindex ones after. */
export function robotsHeader(url: URL, indexable: boolean = config.indexable): string | null {
  return !indexable || alwaysNoindex(url) ? NOINDEX : null;
}

export function robotsTxt(indexable: boolean = config.indexable): string {
  return indexable
    ? `User-agent: *\nAllow: /\nDisallow: /api/\nDisallow: /admin/\n\nSitemap: ${config.siteUrl}/sitemap.xml\n`
    : "# Preview build: not for search engines.\nUser-agent: *\nDisallow: /\n";
}

// Cloudflare Web Analytics (cookieless, aggregate; disclosed on /privacy): the zone injects its beacon script
// from static.cloudflareinsights.com, which reports to cloudflareinsights.com.
export const CF_ANALYTICS = { script: "https://static.cloudflareinsights.com", beacon: "https://cloudflareinsights.com" };

// The theme script runs inline before the first paint (a blocking /assets/theme.js cost ~0.5 s on mobile, pass #38),
// allowed by its hash. tests/unit/speed.test.ts recomputes the hash from THEME_INLINE, so the two can't drift apart.
// Pass #81: the visitor's saved choice ("dark" or "light") wins; with none, the system preference decides.
export const THEME_INLINE = `var t=null;try{t=localStorage.getItem("theme")}catch(e){}if(t==="dark"||t!=="light"&&window.matchMedia&&matchMedia("(prefers-color-scheme: dark)").matches)document.documentElement.dataset.theme="dark"`;
export const THEME_INLINE_SHA256 = "bIoYRI1ODc2jhH7bDdg6D32l0VCGdsgjgmJdrg0bC5g=";

// dnsmailcheck pass #114: plus the hit script a tagged landing carries (src/lib/hits.ts HIT_INLINE), also by its hash.
const CSP = `default-src 'self'; script-src 'self' 'sha256-${THEME_INLINE_SHA256}' 'sha256-${HIT_INLINE_SHA256}' ${CF_ANALYTICS.script}; style-src 'self'; img-src 'self' data:; connect-src 'self' ${CF_ANALYTICS.beacon}; form-action 'self'; frame-ancestors 'none'; base-uri 'none'`;

/**
 * Headers on every response. Static assets get them from public/_headers; the Worker adds the same to its own,
 * with X-Robots-Tag per URL (robotsHeader).
 */
export function siteHeaders(indexable: boolean = config.indexable): Record<string, string> {
  return {
    // HTTPS only from now on (pass #41): a year, this host only (no includeSubDomains, no preload).
    "Strict-Transport-Security": HSTS,
    "X-Content-Type-Options": "nosniff",
    "Referrer-Policy": "strict-origin-when-cross-origin",
    "X-Frame-Options": "DENY",
    "Permissions-Policy": "camera=(), microphone=(), geolocation=(), interest-cohort=()",
    ...(indexable ? {} : { "X-Robots-Tag": NOINDEX }),
  };
}

export const HTML_CSP = CSP;

export const HSTS = "max-age=31536000";

/**
 * Static files the build doesn't version (icons, the share image, the simple pages' theme script): cached a day
 * (pass #41), so a change still reaches everyone by the next day. Versioned /assets/*?v= get a year (worker.ts).
 * styles.css and app.js without ?v= keep revalidating: the Worker's simple pages load them unversioned.
 */
export const DAY_CACHED = new Set(["/favicon.svg", "/favicon.ico", "/apple-touch-icon.png", "/icon-192.png", "/icon-512.png", "/og.png", "/assets/theme.js"]);
export const DAY_CACHE = "public, max-age=86400";

/** public/_headers for the static assets (the Worker's own responses get siteHeaders() in code). */
export function headersFile(indexable: boolean = config.indexable): string {
  const lines = Object.entries({ ...siteHeaders(indexable), "Content-Security-Policy": CSP }).map(([k, v]) => `  ${k}: ${v}`);
  return `# Generated by scripts/build.ts from src/site/seo.ts. Static assets only; Worker responses get the same headers in src/worker.ts.\n/*\n${lines.join("\n")}\n`;
}
